"""Minecraft Discovery Lab: benchmark multiple trials in ONE MCio process.

This is a *soft-reset* throughput experiment, NOT independent-world training.
It teleports the player back, clears inventory/effects, and restores day/health,
but leaves terrain changes and explored chunks in the world. For true fresh
world episodes we'll need world snapshot/reload support later.

Designed for mcio_ctrl 1.5.2 and the existing DemoInstance installation.
"""

import argparse
import random
import time
from pathlib import Path

from mcio_ctrl import controller, instance, network, types, world
from mcio_ctrl.envs import env_util, mcio_env

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "mcio-data"
INSTANCE = "DemoInstance"
SOURCE = "DemoWorld"
TRIAL = "MDL_PersistentBenchmark_v1"
BUTTONS = ("W", "A", "S", "D", "SPACE", "LEFT_BUTTON", "RIGHT_BUTTON")


def send(ctrl, packet):
    ctrl.send_action(packet)
    observation = ctrl.recv_observation()
    if observation.version != network.MCIO_PROTOCOL_VERSION:
        raise RuntimeError("Invalid MCio observation packet")
    return observation


def reset_player(ctrl, start, max_wait=120):
    """Soft reset; intentionally does NOT restore the world or its random seed."""
    # This test world was generated by MCio, enabling immediate respawn.
    for _ in range(max_wait):
        obs = send(ctrl, network.ActionPacket(clear_input=True))
        if obs.health > 0:
            break
    else:
        raise RuntimeError("Player never returned to alive state after death")

    x, y, z, yaw, pitch = start
    reset_cmds = [
        "gamemode survival @s",
        f"tp @s {x:.5f} {y:.5f} {z:.5f} {yaw:.3f} {pitch:.3f}",
        "clear @s",
        "effect clear @s",
        "effect give @s minecraft:instant_health 1 5 true",
        "effect give @s minecraft:saturation 1 20 true",
        "time set day",
        "weather clear",
    ]
    obs = send(ctrl, network.ActionPacket(clear_input=True, commands=reset_cmds))
    # Allow the integrated server to apply the queued commands and send a new observation.
    for _ in range(20):
        obs = send(ctrl, network.ActionPacket())
    return obs


def run_segment(ctrl, rng, max_steps, first_obs):
    manager = env_util.InputStateManager()
    obs = first_obs
    beginning = time.perf_counter()
    reason = "step_limit"
    completed = 0
    for i in range(max_steps):
        if i % 25 == 0:
            pressed = {name: 0 for name in BUTTONS}
            direction = rng.choice(("W", "A", "S", "D", None))
            if direction:
                pressed[direction] = 1
            pressed["SPACE"] = int(rng.random() < 0.25)
            pressed["LEFT_BUTTON"] = int(rng.random() < 0.4)
            pressed["RIGHT_BUTTON"] = int(rng.random() < 0.1)
            events = manager.process_action(pressed, mcio_env.INPUT_MAP)
            cursor = (
                obs.cursor_pos[0] + rng.randrange(-30, 31),
                obs.cursor_pos[1] + rng.randrange(-15, 16),
            )
            pkt = network.ActionPacket(inputs=events, cursor_pos=[cursor])
        else:
            pkt = network.ActionPacket()  # Keep held buttons, advance one tick.
        obs = send(ctrl, pkt)
        completed += 1
        if obs.health == 0:
            reason = "death"
            break
    seconds = time.perf_counter() - beginning
    return obs, completed, seconds, reason


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--episodes", type=int, default=5)
    parser.add_argument("--steps", type=int, default=1000)
    parser.add_argument("--visible", action="store_true", help="Show Minecraft window")
    args = parser.parse_args()
    if args.episodes <= 0 or args.steps <= 0:
        parser.error("Episodes and steps must be positive")

    total_started = time.perf_counter()
    worlds = world.WorldManager(mcio_dir=DATA)
    print(f"Copying original template into disposable {TRIAL} ...", flush=True)
    worlds.copy("storage", SOURCE, INSTANCE, TRIAL, force=True)
    opts = types.RunOptions(
        mcio_dir=DATA,
        instance_name=INSTANCE,
        world_name=TRIAL,
        mcio_mode=types.MCioMode.SYNC,
        hide_window=not args.visible,
        gpu_lib=None if args.visible else "nvidia",
        width=320,
        height=180,
    )
    launcher = instance.Launcher(opts)
    ctrl = None
    total_steps = 0
    active_seconds = 0.0
    try:
        launcher.launch(wait=False)
        ctrl = controller.ControllerSync(
            action_port=opts.action_port,
            observation_port=opts.observation_port,
            connection_timeout=120,
        )
        first = send(ctrl, network.ActionPacket(clear_input=True))
        # Record a reference location; do not derive it from the random player's movement.
        start = (*first.player_pos, first.player_yaw, first.player_pitch)
        rng = random.Random(42)
        print("Game started. Running soft-reset segments in ONE Minecraft process.", flush=True)
        for episode in range(1, args.episodes + 1):
            if episode > 1:
                started = time.perf_counter()
                first = reset_player(ctrl, start)
                print(f"  soft reset: {time.perf_counter() - started:.2f}s", flush=True)
            last, count, elapsed, reason = run_segment(ctrl, rng, args.steps, first)
            total_steps += count
            active_seconds += elapsed
            rate = count / elapsed if elapsed else 0.0
            print(
                f"Episode {episode}/{args.episodes}: {reason}, {count} steps, "
                f"{rate:.1f} steps/s, health={last.health:g}, "
                f"pos={tuple(round(v, 1) for v in last.player_pos)}",
                flush=True,
            )
    finally:
        if ctrl is not None:
            try:
                ctrl.send_stop()
            except Exception as exc:
                print(f"MCio stop warning: {exc}", flush=True)
            ctrl.close()
        launcher.close()

    elapsed_total = time.perf_counter() - total_started
    print("\nRESULTS", flush=True)
    print(f"  Active: {total_steps} steps / {active_seconds:.2f}s = {total_steps / active_seconds:.1f} steps/s")
    print(f"  Whole run: {total_steps} steps / {elapsed_total:.2f}s = {total_steps / elapsed_total:.1f} steps/s")
    print("  IMPORTANT: These are soft resets in the SAME world, not clean-world episodes.")
    print("  No AI training occurs in this benchmark.")


if __name__ == "__main__":
    main()
